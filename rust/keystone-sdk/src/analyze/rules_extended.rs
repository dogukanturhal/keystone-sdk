use std::collections::BTreeSet;
use std::sync::LazyLock;

use regex::Regex;

use super::{finding, statement_matches, Analyzer, Finding, LintLevel, Migration};

macro_rules! re {
    ($name:ident, $pat:expr) => {
        static $name: LazyLock<Regex> = LazyLock::new(|| Regex::new($pat).expect($pat));
    };
}

re!(RE_SERIAL, r"(?i)\b(SERIAL|BIGSERIAL|SMALLSERIAL)\b");
re!(RE_TIMESTAMP_TOKEN, r"(?i)\bTIMESTAMP\b");
re!(
    RE_TIMESTAMP_WITH_TZ,
    r"(?i)\bTIMESTAMP\s+(?:WITH\s+TIME\s+ZONE|TZ)\b|\bTIMESTAMPTZ\b"
);
re!(
    RE_RESERVED_IDENTIFIER,
    r"(?i)\b(?:CREATE\s+TABLE|ADD\s+COLUMN|ALTER\s+COLUMN)\s+(user|order|group|type|table|role|schema|index)\b"
);
re!(RE_CASCADE_DELETE, r"(?i)\bON\s+DELETE\s+CASCADE\b");
re!(RE_FOREIGN_KEY, r"(?i)\bFOREIGN\s+KEY\s*\(\s*(\w+)");
re!(RE_INDEX_ON_COL, r"(?i)\bINDEX\b[^;]*\(\s*(\w+)");
re!(
    RE_SET_STORAGE,
    r"(?i)\bALTER\s+COLUMN\s+\w+\s+SET\s+STORAGE\b"
);
re!(RE_PUBLIC_SCHEMA, r"(?i)\bpublic\.[a-z_][a-z0-9_]*");
re!(
    RE_RENAME_TABLE,
    r"(?i)\bALTER\s+TABLE\s+\w+\s+RENAME\s+TO\b"
);

/// no-serial
pub struct NoSerial;
impl Analyzer for NoSerial {
    fn id(&self) -> &'static str {
        "no-serial"
    }
    fn description(&self) -> &'static str {
        "SERIAL/BIGSERIAL are legacy; use GENERATED BY DEFAULT AS IDENTITY"
    }
    fn check(&self, m: &Migration) -> Vec<Finding> {
        statement_matches(
            m,
            &RE_SERIAL,
            LintLevel::Warning,
            self.id(),
            "SERIAL/BIGSERIAL/SMALLSERIAL are PostgreSQL pseudo-types backed by \
             a sequence + default. Use GENERATED BY DEFAULT AS IDENTITY \
             (SQL-standard, cleaner ownership semantics on CREATE/DROP)",
        )
    }
}

/// require-timestamptz
pub struct RequireTimestamptz;
impl Analyzer for RequireTimestamptz {
    fn id(&self) -> &'static str {
        "require-timestamptz"
    }
    fn description(&self) -> &'static str {
        "use TIMESTAMPTZ instead of TIMESTAMP (time zone awareness)"
    }
    fn check(&self, m: &Migration) -> Vec<Finding> {
        let mut out = Vec::new();
        for f in &m.files {
            for (i, line) in f.body.split('\n').enumerate() {
                if !RE_TIMESTAMP_TOKEN.is_match(line) {
                    continue;
                }
                if RE_TIMESTAMP_WITH_TZ.is_match(line) {
                    continue;
                }
                out.push(finding(
                    self.id(),
                    LintLevel::Warning,
                    &f.name,
                    (i + 1) as i32,
                    "TIMESTAMP (without time zone) stores the local clock with no offset. \
                     Use TIMESTAMPTZ (alias for TIMESTAMP WITH TIME ZONE) unless you \
                     have a specific reason to store naive local time",
                ));
            }
        }
        out
    }
}

