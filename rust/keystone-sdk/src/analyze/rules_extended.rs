#[cfg(test)]
mod tests {
    use super::super::{FileBody, Migration};
    use super::*;

    fn mig(body: &str) -> Migration {
        Migration {
            files: vec![FileBody {
                name: "001.sql".into(),
                body: body.into(),
            }],
            ..Default::default()
        }
    }

    #[test]
    fn no_serial() {
        assert_eq!(NoSerial.check(&mig("id BIGSERIAL")).len(), 1);
        assert_eq!(NoSerial.check(&mig("id bigint")).len(), 0);
    }

    #[test]
    fn require_timestamptz_filters_tz() {
        assert_eq!(RequireTimestamptz.check(&mig("ts TIMESTAMP")).len(), 1);
        assert_eq!(
            RequireTimestamptz
                .check(&mig("ts TIMESTAMP WITH TIME ZONE"))
                .len(),
            0
        );
        assert_eq!(RequireTimestamptz.check(&mig("ts TIMESTAMPTZ")).len(), 0);
    }

    #[test]
    fn require_index_on_fk() {
        // FK with no index → fires.
        let f = RequireIndexOnFk.check(&mig(
            "CREATE TABLE t (a int, FOREIGN KEY (a) REFERENCES p(id));",
        ));
        assert_eq!(f.len(), 1);
        // FK plus an index on the same col → no finding.
        let f = RequireIndexOnFk.check(&mig(
            "CREATE TABLE t (a int, FOREIGN KEY (a) REFERENCES p(id));\nCREATE INDEX ix ON t (a);",
        ));
        assert_eq!(f.len(), 0);
    }

    #[test]
    fn public_schema_skipped_when_target_public() {
        let mut m = mig("SELECT * FROM public.t;");
        m.target_schema = "tenant_1".into();
        assert_eq!(NoExplicitPublicSchema.check(&m).len(), 1);
        m.target_schema = "public".into();
        assert_eq!(NoExplicitPublicSchema.check(&m).len(), 0);
    }

    #[test]
    fn require_migration_comment() {
        assert_eq!(
            RequireMigrationComment
                .check(&mig("CREATE TABLE t (id int);"))
                .len(),
            1
        );
        assert_eq!(
            RequireMigrationComment
                .check(&mig("-- add t\nCREATE TABLE t (id int);"))
                .len(),
            0
        );
    }

    #[test]
    fn max_migration_size() {
        let big = "x\n".repeat(201);
        assert_eq!(MaxMigrationSize.check(&mig(&big)).len(), 1);
        let small = "x\n".repeat(10);
        assert_eq!(MaxMigrationSize.check(&mig(&small)).len(), 0);
    }
}
