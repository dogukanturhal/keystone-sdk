/// no-explicit-public-schema
pub struct NoExplicitPublicSchema;
impl Analyzer for NoExplicitPublicSchema {
    fn id(&self) -> &'static str {
        "no-explicit-public-schema"
    }
    fn description(&self) -> &'static str {
        "hardcoded 'public' schema prefix breaks multi-tenant rollout"
    }
    fn check(&self, m: &Migration) -> Vec<Finding> {
        // Skip when target schema is actually public — that's expected.
        if m.target_schema.eq_ignore_ascii_case("public") {
            return Vec::new();
        }
        statement_matches(
            m,
            &RE_PUBLIC_SCHEMA,
            LintLevel::Warning,
            self.id(),
            "hardcoded 'public.table' prefix. Keystone's runner sets \
             search_path=<target_schema>, so unqualified names resolve \
             per-tenant. Explicit 'public' prefix routes writes to the \
             wrong schema in multi-tenant rollouts.",
        )
    }
}

/// require-migration-comment
pub struct RequireMigrationComment;
impl Analyzer for RequireMigrationComment {
    fn id(&self) -> &'static str {
        "require-migration-comment"
    }
    fn description(&self) -> &'static str {
        "first line of migration should be a SQL comment explaining the change"
    }
    fn check(&self, m: &Migration) -> Vec<Finding> {
        let mut out = Vec::new();
        for f in &m.files {
            // Walk to the first non-blank line; require it start with "--".
            for line in f.body.split('\n') {
                let t = line.trim();
                if t.is_empty() {
                    continue;
                }
                if !t.starts_with("--") {
                    out.push(finding(
                        self.id(),
                        LintLevel::Notice,
                        &f.name,
                        1,
                        "first non-blank line is not an SQL comment. Add a one-line summary of the migration's intent for future archaeologists.",
                    ));
                }
                break;
            }
        }
        out
    }
}

