/// max-migration-size (default cap 200 newlines)
pub struct MaxMigrationSize;
impl Analyzer for MaxMigrationSize {
    fn id(&self) -> &'static str {
        "max-migration-size"
    }
    fn description(&self) -> &'static str {
        "large migrations are harder to review and roll back"
    }
    fn check(&self, m: &Migration) -> Vec<Finding> {
        const CAP: usize = 200;
        let mut out = Vec::new();
        for f in &m.files {
            let n = f.body.matches('\n').count();
            if n > CAP {
                out.push(finding(
                    self.id(),
                    LintLevel::Notice,
                    &f.name,
                    0,
                    format!(
                        "migration is {n} lines (> {CAP}) — \
                         consider splitting into smaller reviewable chunks; \
                         Keystone's runner already applies each file in its own transaction"
                    ),
                ));
            }
        }
        out
    }
}

