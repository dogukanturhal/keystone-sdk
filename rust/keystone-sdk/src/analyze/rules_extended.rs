/// require-index-on-fk
pub struct RequireIndexOnFk;
impl Analyzer for RequireIndexOnFk {
    fn id(&self) -> &'static str {
        "require-index-on-fk"
    }
    fn description(&self) -> &'static str {
        "foreign key columns must have an index (parent delete = full-table scan without)"
    }
    fn check(&self, m: &Migration) -> Vec<Finding> {
        let mut out = Vec::new();
        for f in &m.files {
            let fk_cols: Vec<String> = RE_FOREIGN_KEY
                .captures_iter(&f.body)
                .filter_map(|c| c.get(1).map(|x| x.as_str().to_lowercase()))
                .collect();
            if fk_cols.is_empty() {
                continue;
            }
            let idx_cols: BTreeSet<String> = RE_INDEX_ON_COL
                .captures_iter(&f.body)
                .filter_map(|c| c.get(1).map(|x| x.as_str().to_lowercase()))
                .collect();
            for col in fk_cols {
                if !idx_cols.contains(&col) {
                    out.push(finding(
                        self.id(),
                        LintLevel::Warning,
                        &f.name,
                        0,
                        format!(
                            "FOREIGN KEY on column {col} has no detected index. \
                             Without one, DELETE on the parent table does a full scan of this \
                             table per parent row. Add CREATE INDEX on the FK column."
                        ),
                    ));
                }
            }
        }
        out
    }
}

