// -- Rule: no-serial (prefer GENERATED … AS IDENTITY) -------------------

type NoSerial struct{}

func (NoSerial) ID() string { return "no-serial" }
func (NoSerial) Description() string {
	return "SERIAL/BIGSERIAL are legacy; use GENERATED BY DEFAULT AS IDENTITY"
}

var reSerial = regexp.MustCompile(`(?i)\b(SERIAL|BIGSERIAL|SMALLSERIAL)\b`)

func (a *NoSerial) Check(_ context.Context, m *Migration) ([]Finding, error) {
	return statementMatches(m, reSerial, keystonev1alpha1.LintLevelWarning,
		a.ID(),
		"SERIAL/BIGSERIAL/SMALLSERIAL are PostgreSQL pseudo-types backed by "+
			"a sequence + default. Use GENERATED BY DEFAULT AS IDENTITY "+
			"(SQL-standard, cleaner ownership semantics on CREATE/DROP)"), nil
}

// -- Rule: require-timestamptz (no timestamp without time zone) ---------

type RequireTimestamptz struct{}

func (RequireTimestamptz) ID() string { return "require-timestamptz" }
func (RequireTimestamptz) Description() string {
	return "use TIMESTAMPTZ instead of TIMESTAMP (time zone awareness)"
}

// Go's RE2 has no negative lookahead; match all TIMESTAMP occurrences and
// filter post-hoc for the TZ-awareness suffix.
var reTimestampToken = regexp.MustCompile(`(?i)\bTIMESTAMP\b`)
var reTimestampWithTZ = regexp.MustCompile(`(?i)\bTIMESTAMP\s+(?:WITH\s+TIME\s+ZONE|TZ)\b|\bTIMESTAMPTZ\b`)

func (a *RequireTimestamptz) Check(_ context.Context, m *Migration) ([]Finding, error) {
	var out []Finding
	for _, f := range m.Files {
		for i, line := range strings.Split(f.Body, "\n") {
			if !reTimestampToken.MatchString(line) {
				continue
			}
			// Accept lines where the TIMESTAMP is followed by "WITH TIME
			// ZONE" / "TZ" or is actually TIMESTAMPTZ.
			if reTimestampWithTZ.MatchString(line) {
				continue
			}
			out = append(out, Finding{
				Rule:     a.ID(),
				Severity: keystonev1alpha1.LintLevelWarning,
				File:     f.Name,
				Line:     int32(i + 1),
				Message: "TIMESTAMP (without time zone) stores the local clock with no offset. " +
					"Use TIMESTAMPTZ (alias for TIMESTAMP WITH TIME ZONE) unless you " +
					"have a specific reason to store naive local time",
			})
		}
	}
	return out, nil
}

// -- Rule: no-reserved-identifier ---------------------------------------

type NoReservedIdentifier struct{}

func (NoReservedIdentifier) ID() string { return "no-reserved-identifier" }
func (NoReservedIdentifier) Description() string {
	return "avoid SQL reserved words as identifiers (user, order, group, etc.)"
}

// Narrow list — the reserved words most commonly used by accident.
// Full list per pg docs is ~280 entries; this covers the footguns.
var reReservedIdentifier = regexp.MustCompile(`(?i)\b(?:CREATE\s+TABLE|ADD\s+COLUMN|ALTER\s+COLUMN)\s+(user|order|group|type|table|role|schema|index)\b`)

func (a *NoReservedIdentifier) Check(_ context.Context, m *Migration) ([]Finding, error) {
	return statementMatches(m, reReservedIdentifier, keystonev1alpha1.LintLevelWarning,
		a.ID(),
		"reserved SQL keyword used as identifier. Every query referencing this "+
			"object must then quote it, and an unquoted reference parses as the keyword. "+
			"Use a non-reserved synonym (users, orders, groups, etc.)"), nil
}

// -- Rule: max-migration-size (lines per file) --------------------------

type MaxMigrationSize struct {
	// MaxLines caps the acceptable line count per migration file.
	// Default 200 per Keystone convention.
	MaxLines int
}

func (MaxMigrationSize) ID() string { return "max-migration-size" }
func (MaxMigrationSize) Description() string {
	return "large migrations are harder to review and roll back"
}

func (a *MaxMigrationSize) Check(_ context.Context, m *Migration) ([]Finding, error) {
	cap := a.MaxLines
	if cap == 0 {
		cap = 200
	}
	var out []Finding
	for _, f := range m.Files {
		n := strings.Count(f.Body, "\n")
		if n > cap {
			out = append(out, Finding{
				Rule:     a.ID(),
				Severity: keystonev1alpha1.LintLevelNotice,
				File:     f.Name,
				Message: "migration is " + itoa(n) + " lines (> " + itoa(cap) + ") — " +
					"consider splitting into smaller reviewable chunks; " +
					"Keystone's runner already applies each file in its own transaction",
			})
		}
	}
	return out, nil
}

