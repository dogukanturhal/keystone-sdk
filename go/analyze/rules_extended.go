// -- Rule: no-explicit-public-schema ------------------------------------

type NoExplicitPublicSchema struct{}

func (NoExplicitPublicSchema) ID() string { return "no-explicit-public-schema" }
func (NoExplicitPublicSchema) Description() string {
	return "hardcoded 'public' schema prefix breaks multi-tenant rollout"
}

var rePublicSchema = regexp.MustCompile(`(?i)\bpublic\.[a-z_][a-z0-9_]*`)

func (a *NoExplicitPublicSchema) Check(_ context.Context, m *Migration) ([]Finding, error) {
	// Skip when target schema is actually public — that's expected.
	if strings.EqualFold(m.TargetSchema, "public") {
		return nil, nil
	}
	return statementMatches(m, rePublicSchema, keystonev1alpha1.LintLevelWarning,
		a.ID(),
		"hardcoded 'public.table' prefix. Keystone's runner sets "+
			"search_path=<target_schema>, so unqualified names resolve "+
			"per-tenant. Explicit 'public' prefix routes writes to the "+
			"wrong schema in multi-tenant rollouts."), nil
}

// -- Rule: require-migration-comment ------------------------------------

type RequireMigrationComment struct{}

func (RequireMigrationComment) ID() string { return "require-migration-comment" }
func (RequireMigrationComment) Description() string {
	return "first line of migration should be a SQL comment explaining the change"
}

func (a *RequireMigrationComment) Check(_ context.Context, m *Migration) ([]Finding, error) {
	var out []Finding
	for _, f := range m.Files {
		// Walk the first non-blank line; require it start with "--".
		for _, line := range strings.Split(f.Body, "\n") {
			t := strings.TrimSpace(line)
			if t == "" {
				continue
			}
			if !strings.HasPrefix(t, "--") {
				out = append(out, Finding{
					Rule:     a.ID(),
					Severity: keystonev1alpha1.LintLevelNotice,
					File:     f.Name,
					Line:     1,
					Message:  "first non-blank line is not an SQL comment. Add a one-line summary of the migration's intent for future archaeologists.",
				})
			}
			break
		}
	}
	return out, nil
}

