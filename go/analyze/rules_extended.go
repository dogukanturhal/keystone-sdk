// -- Rule: require-index-on-fk ------------------------------------------

type RequireIndexOnFK struct{}

func (RequireIndexOnFK) ID() string { return "require-index-on-fk" }
func (RequireIndexOnFK) Description() string {
	return "foreign key columns must have an index (parent delete = full-table scan without)"
}

// Intentionally coarse: flag FOREIGN KEY declarations in files that
// don't also have an INDEX on the same column. Matches the heuristic
// squawk uses.
var reForeignKey = regexp.MustCompile(`(?i)\bFOREIGN\s+KEY\s*\(\s*(\w+)`)
var reIndexOnCol = regexp.MustCompile(`(?i)\bINDEX\b[^;]*\(\s*(\w+)`)

func (a *RequireIndexOnFK) Check(_ context.Context, m *Migration) ([]Finding, error) {
	var out []Finding
	for _, f := range m.Files {
		fkCols := reForeignKey.FindAllStringSubmatch(f.Body, -1)
		if len(fkCols) == 0 {
			continue
		}
		idxCols := make(map[string]bool)
		for _, m := range reIndexOnCol.FindAllStringSubmatch(f.Body, -1) {
			if len(m) > 1 {
				idxCols[strings.ToLower(m[1])] = true
			}
		}
		for _, fk := range fkCols {
			if len(fk) < 2 {
				continue
			}
			col := strings.ToLower(fk[1])
			if !idxCols[col] {
				out = append(out, Finding{
					Rule:     a.ID(),
					Severity: keystonev1alpha1.LintLevelWarning,
					File:     f.Name,
					Message: "FOREIGN KEY on column " + col + " has no detected index. " +
						"Without one, DELETE on the parent table does a full scan of this " +
						"table per parent row. Add CREATE INDEX on the FK column.",
				})
			}
		}
	}
	return out, nil
}

