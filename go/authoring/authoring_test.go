func TestNextVersion(t *testing.T) {
	tests := []struct {
		name     string
		existing []string
		want     string
	}{
		{"empty", nil, "001"},
		{"single", []string{"001_init.up.sql"}, "002"},
		{"gap", []string{"001_a.up.sql", "002_b.up.sql", "005_c.up.sql"}, "006"},
		{"down-files-ignored-dupes", []string{"001_a.up.sql", "001_a.down.sql"}, "002"},
		{"wider-width", []string{"0001_a.up.sql", "0002_b.up.sql"}, "0003"},
		{"non-numeric-skipped", []string{"baseline.up.sql", "002_x.up.sql"}, "003"},
		{"paths", []string{"migrations/007_x.up.sql"}, "008"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := NextVersion(tt.existing); got != tt.want {
				t.Errorf("NextVersion(%v) = %q, want %q", tt.existing, got, tt.want)
			}
		})
	}
}

