// TestRenderUpDown_LintClean asserts that a generated forward file passes
// the cluster-side analyzer with zero error-severity findings — i.e. the
// renderer produces lint-clean migrations by construction.
func TestRenderUpDown_LintClean(t *testing.T) {
	plan := &declarative.Plan{
		Statements: []string{
			"CREATE TABLE accounts (\n    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n    email TEXT NOT NULL,\n    created_at TIMESTAMPTZ NOT NULL DEFAULT now()\n)",
			"CREATE INDEX idx_accounts_email_lower ON accounts (LOWER(email))",
		},
		ReverseStatements: []string{
			"DROP TABLE IF EXISTS accounts",
			"DROP INDEX CONCURRENTLY IF EXISTS idx_accounts_email_lower",
		},
	}
	b := RenderUpDown(plan, Options{Name: "create_accounts", Version: "001", Schema: "app", GeneratedBy: "test"})

	m := &analyze.Migration{
		BundleName:   "authoring-test",
		Version:      "001",
		TargetSchema: "app",
		Files:        []analyze.FileBody{{Name: b.UpFile, Body: b.Up}},
	}
	findings, err := analyze.DefaultRegistry().Run(context.Background(), m)
	if err != nil {
		t.Fatalf("analyzer error: %v", err)
	}
	for _, f := range findings {
		if f.Severity == keystonev1alpha1.LintLevelError {
			t.Errorf("generated up.sql has an error-severity finding %q: %s", f.Rule, f.Message)
		}
	}
}

func TestRenderUpDown_StripSchema(t *testing.T) {
	plan := &declarative.Plan{
		Statements: []string{
			`CREATE TABLE "app"."orders" (id bigint, customer_id bigint, FOREIGN KEY (customer_id) REFERENCES "app"."customers" (id))`,
		},
		ReverseStatements: []string{
			`DROP TABLE IF EXISTS "app"."orders"`,
		},
	}
	b := RenderUpDown(plan, Options{Name: "create_orders", Version: "002", Schema: "app", StripSchema: "app"})
	if strings.Contains(b.Up, `"app".`) {
		t.Errorf("up still contains schema qualifier after StripSchema:\n%s", b.Up)
	}
	if !strings.Contains(b.Up, `CREATE TABLE "orders"`) {
		t.Errorf("up missing schema-relative table:\n%s", b.Up)
	}
	if !strings.Contains(b.Up, `REFERENCES "customers"`) {
		t.Errorf("up FK not made schema-relative:\n%s", b.Up)
	}
	if strings.Contains(b.Down, `"app".`) {
		t.Errorf("down still contains schema qualifier:\n%s", b.Down)
	}
}

func TestRenderUpDown_NilPlan(t *testing.T) {
	b := RenderUpDown(nil, Options{Name: "noop", Version: "001"})
	if !strings.Contains(b.Up, "SET LOCAL statement_timeout") {
		t.Errorf("nil plan up should still have a header:\n%s", b.Up)
	}
	if !strings.Contains(b.Down, "rollback_note") {
		t.Errorf("nil plan down should carry the rollback_note:\n%s", b.Down)
	}
	files := b.Files()
	if len(files) != 2 {
		t.Errorf("Files() returned %d entries, want 2", len(files))
	}
}
